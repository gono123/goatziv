// node timing.js — speaks every line once (cached in out/.vo-cache), measures it, and lays the lines
// end to end with breathing room. Writes timeline.js, which score.js reads in Node and the browser.
const fs = require('fs');
const path = require('path');
const Voice = require('./engine/audio/voice');
const { LINES, VOICES, SCENES } = require('./lines');

const OUT = path.join(__dirname, 'out');
fs.mkdirSync(OUT, { recursive: true });
const spec = LINES.map((l) => ({ at: 0, text: l.text, who: l.who, voice: VOICES[l.who].voice, rate: VOICES[l.who].rate }));
const vo = Voice.speak(spec, { out: OUT, save: false, engine: 'kokoro-onnx' });

const START = 1.2;
let t = START;
const lines = [];
const scenes = [];
LINES.forEach((l, i) => {
  const dur = vo.lines[i].end - vo.lines[i].t;
  const prev = LINES[i - 1];
  if (prev && prev.scene !== l.scene) t += 0.9; // a breath between scenes
  else if (prev && prev.who !== l.who) t += 0.2;
  if (!prev || prev.scene !== l.scene) scenes.push({ id: l.scene, t0: Math.max(0, t - (prev ? 0.45 : START)) });
  lines.push({ at: +t.toFixed(3), dur: +dur.toFixed(3), text: l.text, who: l.who, scene: l.scene });
  const tail = /\.\.\.$/.test(l.text) ? 0.55 : /\?$/.test(l.text) ? 0.42 : 0.26;
  t += dur + tail;
});
scenes.forEach((s, i) => { s.t1 = i + 1 < scenes.length ? scenes[i + 1].t0 : t + 4.5; });
const DURATION = +(t + 4.5).toFixed(2);
const TL = { DURATION, lines, scenes: scenes.map((s) => ({ id: s.id, t0: +s.t0.toFixed(3), t1: +s.t1.toFixed(3) })) };
fs.writeFileSync(path.join(__dirname, 'timeline.js'), `// generated by timing.js: do not edit\n(function () { const TL = ${JSON.stringify(TL)};\nif (typeof module !== 'undefined') module.exports = TL; else globalThis.TIMELINE = TL; })();\n`);
console.log(`timeline.js  ${lines.length} lines, ${scenes.length} scenes, ${DURATION.toFixed(1)}s (${(DURATION / 60).toFixed(2)} min)`);
for (const s of TL.scenes) console.log(`  ${s.id.padEnd(8)} ${s.t0.toFixed(1).padStart(6)} → ${s.t1.toFixed(1).padStart(6)}  (${(s.t1 - s.t0).toFixed(1)}s)`);
